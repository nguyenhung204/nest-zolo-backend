// ============= Batch Avatar URL Resolution =============

/**
 * DTO for resolving presigned URLs for multiple avatar mediaIds at once.
 * Used by Gateway to enrich conversation list/detail responses.
 */
export class GetAvatarsBatchDto {
  @IsString({ each: true })
  mediaIds!: string[];

  /**
   * Which variant to resolve.
   * - 'thumb'    (default): prefer thumbnail generated by media-worker; falls back to original.
   * - 'original': always return the original uploaded file URL.
   */
  @IsOptional()
  @IsIn(['thumb', 'original'])
  variant?: 'thumb' | 'original';
}

/**
 * Per-entry result: includes expiresAt so Gateway can compute a smart Redis TTL
 * instead of using a fixed duration.
 */
export class AvatarUrlEntry {
  url!: string;
  /** Unix milliseconds when the presigned URL expires */
  expiresAt!: number;
}

export class AvatarUrlsResponseDto {
  /** Map of mediaId → AvatarUrlEntry. Missing/unauthorized IDs are silently omitted. */
  urls!: Record<string, AvatarUrlEntry>;
}
